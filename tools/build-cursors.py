#!/usr/bin/env python3
"""Rasterizes the accepted Meridian cursor set (tools/design/cursor-concept.py: the shapes,
hotspots and both variants) into src/Gui/Graphics/CursorImages.g.cs.

Every cursor is drawn at 24, 32 and 48 px (rsvg-convert), premultiplied ARGB, and stored as
runs: a byte of repeat count (1..255) then the pixel (little endian), one image after another.
Run after changing the shapes; the kernel build does not need Python or rsvg."""
import base64, importlib.util, struct, subprocess, sys, tempfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('concept', ROOT / 'tools/design/cursor-concept.py')
concept = importlib.util.module_from_spec(spec); spec.loader.exec_module(concept)
SIZES = (24, 32, 48)
VARIANTS = ('Light', 'Dark')
DEFS = '<defs><filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation=".7"/></filter></defs>'


def render(name, kind, data, variant, size, work):
    body, outline = concept.VARIANTS[variant]
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">{DEFS}'
           + concept.glyph(name, kind, data, body, outline) + '</svg>')
    source, target = work / 'c.svg', work / 'c.png'
    source.write_text(svg)
    subprocess.run(['rsvg-convert', '-w', str(size), '-h', str(size), str(source), '-o', str(target)], check=True)
    image = Image.open(target).convert('RGBA')
    raw = image.tobytes(); pixels = []
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i], raw[i + 1], raw[i + 2], raw[i + 3]
        pixels.append((a << 24) | ((r * a // 255) << 16) | ((g * a // 255) << 8) | (b * a // 255))
    return pixels


def runs(pixels):
    out = bytearray(); i = 0
    while i < len(pixels):
        n = 1
        while i + n < len(pixels) and n < 255 and pixels[i + n] == pixels[i]: n += 1
        out += bytes((n,)) + struct.pack('<I', pixels[i]); i += n
    return out


def main(output):
    blob = bytearray(); table = []
    with tempfile.TemporaryDirectory(prefix='zenith-cursors-') as temporary:
        work = Path(temporary)
        for v, variant in enumerate(VARIANTS):
            for s, (name, label, hot, kind, data) in enumerate(concept.SHAPES):
                for size in SIZES:
                    encoded = runs(render(name, kind, data, variant, size, work))
                    table.append((v, s, size, len(blob), len(encoded), round(hot[0] * size / 24), round(hot[1] * size / 24)))
                    blob += encoded
    names = [shape[0] for shape in concept.SHAPES]
    lines = ['// Generated by tools/build-cursors.py from tools/design/cursor-concept.py (the accepted Meridian set).',
             'namespace Zenith.Gui.Graphics;', '',
             'internal static partial class CursorImages', '{',
             '    /// <summary>CSS names, in CursorShape order.</summary>',
             '    public static readonly string[] Names = { ' + ', '.join('"' + n + '"' for n in names) + ' };',
             '    public static readonly int[] Sizes = { ' + ', '.join(map(str, SIZES)) + ' };',
             '    /// <summary>Per image: variant, shape, size, offset and length in the runs, hotspot x and y.</summary>',
             '    private static readonly int[] Table =', '    {']
    for row in table: lines.append('        ' + ', '.join(map(str, row)) + ',')
    lines += ['    };', '    private const string Runs =']
    text = base64.b64encode(bytes(blob)).decode()
    for i in range(0, len(text), 120): lines.append('        "' + text[i:i + 120] + '"' + (';' if i + 120 >= len(text) else ' +'))
    lines += ['}', '']
    Path(output).write_text('\n'.join(lines))
    print(f'{len(table)} images, {len(blob)} bytes of runs')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else ROOT / 'src/Gui/Graphics/CursorImages.g.cs')
