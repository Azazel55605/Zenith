#!/usr/bin/env python3
"""Cross-build the NetSurf 3.11 rendering core and its C dependencies with the Zenith SDK."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import fcntl
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor/netsurf"
RESOURCES = ("Messages", "default.css", "internal.css", "adblock.css", "quirks.css", "SearchEngines", "credits.html", "licence.html")
LIBS = ("libwapcaplet", "libparserutils", "libhubbub", "libcss", "libdom", "libnsutils", "libnsbmp", "libnsgif")


def run(args, **kwargs):
    return subprocess.run(args, check=True, **kwargs)


CSS_OVERLAYS = ("grid", "math", "variables")


def source_inputs():
    yield VENDOR / "sources.tar.xz"
    yield from sorted(VENDOR.glob("*.patch"))
    yield VENDOR / "layout_grid.c"
    for overlay in CSS_OVERLAYS:
        yield from sorted(p for p in (VENDOR / overlay).rglob("*") if p.is_file())


def hash_files(files):
    digest = hashlib.sha256()
    for path in files:
        digest.update(str(path.resolve().relative_to(ROOT)).encode() + b"\0")
        digest.update(hashlib.sha256(path.read_bytes()).digest())
    return digest


def extract(output):
    digest = hash_files(source_inputs()).hexdigest()
    stamp = output / ".sources"
    if stamp.is_file() and stamp.read_text() == digest:
        return
    # Stage once under the existing build lock. Removed patches or overlay
    # sources must disappear from the next archive, including after a retry.
    with tempfile.TemporaryDirectory(dir=output, prefix=".source-") as tmp:
        stage = Path(tmp)
        with tarfile.open(VENDOR / "sources.tar.xz") as src:
            src.extractall(stage, filter="data")
        upstream = stage / "netsurf-all-3.11"
        for patch in sorted(VENDOR.glob("*.patch")):
            project = patch.name.partition("-")[0]
            if project not in ("libcss", "libdom"):
                project = "netsurf"
            run(["patch", "--batch", "--fuzz=0", "-p1", "-i", patch], cwd=upstream / project)
        for overlay in CSS_OVERLAYS:
            if (VENDOR / overlay).is_dir():
                shutil.copytree(VENDOR / overlay, upstream / "libcss", dirs_exist_ok=True)
        shutil.copyfile(VENDOR / "layout_grid.c", upstream / "netsurf/content/handlers/html/layout_grid.c")
        stamp.unlink(missing_ok=True)
        for tree in list(stage.iterdir()):
            installed = output / tree.name
            if installed.exists():
                installed.rename(stage / (".old-" + tree.name))
            tree.rename(installed)
        stamp.write_text(digest)


def generate_bindings(upstream, out, compiler, env):
    generator = upstream / "nsgenbind"
    executable = out / "nsgenbind"
    run([compiler, "-std=gnu11", "-D_DEFAULT_SOURCE", "-DYYENABLE_NLS=0", "-Isrc", "-Igenerated",
         *sorted(Path("src") / p.name for p in (generator / "src").glob("*.c")),
         *sorted(Path("generated") / p.name for p in (generator / "generated").glob("*.c")),
         "-lm", "-o", executable], cwd=generator, env=env)
    core = upstream / "netsurf"
    js = Path("content/handlers/javascript")
    bindings = Path("generated-js/duktape")
    (core / bindings).mkdir(parents=True, exist_ok=True)
    run([executable, "-I", js / "WebIDL", js / "duktape/netsurf.bnd", bindings], cwd=core, env=env)
    for script in ("polyfill", "generics"):
        data = (core / js / "duktape" / (script + ".js")).read_bytes()
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
        name = script + "_js"
        (core / bindings / (script + ".js.inc")).write_text(
            f"static const unsigned char {name}[] = {{\n" + ",\n".join(rows) +
            f"\n}};\nstatic const unsigned int {name}_len = sizeof({name});\n")


def generate(upstream, out):
    compiler = os.environ.get("CC_FOR_BUILD", "cc")
    env = dict(os.environ, PERL_HASH_SEED="0", PERL_PERTURB_KEYS="0", PYTHONHASHSEED="0", LC_ALL="C")
    for lib, script in (("libparserutils", "make-aliases.pl"), ("libhubbub", "make-entities.pl")):
        run(["perl", "build/" + script], cwd=upstream / lib, env=env)
    generated_table = upstream / "libhubbub/src/treebuilder/autogenerated-element-type.c"
    shutil.copyfile(VENDOR / "hubbub-element-type.inc", generated_table)
    properties = upstream / "libcss/src/parse/properties"
    run([sys.executable, "-B", "src/select/select_generator.py"], cwd=upstream / "libcss", env=env)
    generator = out / "gen-css"
    run([compiler, properties / "css_property_parser_gen.c", "-o", generator])
    for definition in (properties / "properties.gen").read_text().splitlines():
        if definition and definition[0] != "#" and ":" in definition:
            prop = definition.split(":", 1)[0]
            run([generator, "-o", "autogenerated_" + prop + ".c", definition], cwd=properties)
    netsurf = upstream / "netsurf"
    generate_bindings(upstream, out, compiler, env)
    run([compiler, "-I.", "tools/split-messages.c", "-lz", "-o", out / "split-messages"], cwd=netsurf)
    resources = out / "resources"
    resources.mkdir(exist_ok=True)
    # The generator records its input pathname in a comment in the installed asset.
    run([out / "split-messages", "-l", "en", "-p", "any", "-i", "resources/FatMessages",
         "-o", resources / "Messages"], cwd=netsurf)
    for name in ("default.css", "internal.css", "adblock.css", "quirks.css", "SearchEngines"):
        shutil.copyfile(netsurf / "resources" / name, resources / name)
    for name in ("credits.html", "licence.html"):
        shutil.copyfile(netsurf / "resources/en" / name, resources / name)


def build_key(sdk, cc, host_cc):
    key = hash_files([Path(__file__), *source_inputs(), *sorted(VENDOR.glob("*.mk")),
                      VENDOR / "testament.h", VENDOR / "hubbub-element-type.inc"])
    for path in sorted((sdk / "include").rglob("*")):
        if path.is_file():
            key.update(str(path.relative_to(sdk)).encode() + b"\0")
            key.update(path.read_bytes())
    for tool in (cc, host_cc, "ar"):
        key.update(subprocess.check_output([tool, "--version"]))
    return key.hexdigest()


def build(out, sdk, jobs):
    out.mkdir(parents=True, exist_ok=True)
    # The package builder and standalone feasibility checks use this same output.
    with (out / ".build-lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        build_locked(out, sdk, jobs)


def build_locked(out, sdk, jobs):
    if not (sdk / "include/stdlib.h").is_file():
        raise SystemExit(f"Build the Zenith C SDK first; missing {sdk}/include/stdlib.h")
    cc = os.environ.get("ZENITH_NETSURF_CC", "gcc")
    key = build_key(sdk, cc, os.environ.get("CC_FOR_BUILD", "cc"))
    stamp = out / ".built"
    if (stamp.is_file() and stamp.read_text() == key and (out / "libnetsurf.a").is_file()
            and (out / "include/dom/dom.h").is_file() and
            all((out / "resources" / name).is_file() for name in RESOURCES)):
        print(f"Using verified build inputs for {out / 'libnetsurf.a'}", flush=True)
        return
    stamp.unlink(missing_ok=True)
    extract(out)
    upstream = out / "netsurf-all-3.11"
    netsurf = upstream / "netsurf"
    zlib = out / "zlib-1.4"
    libpng = out / "libpng-1.6.59"
    jpeg = out / "jpeg-10"
    headers = out / "include"
    objects = out / "objects"
    headers.mkdir(exist_ok=True)
    objects.mkdir(exist_ok=True)
    generate(upstream, out)
    for name in LIBS:
        shutil.copytree(upstream / name / "include", headers, dirs_exist_ok=True)
    binding = headers / "dom/bindings/hubbub"
    binding.mkdir(parents=True, exist_ok=True)
    for name in ("errors.h", "parser.h"):
        shutil.copyfile(upstream / "libdom/bindings/hubbub" / name, binding / name)
    for name in ("zlib.h", "zconf.h"):
        shutil.copyfile(zlib / name, headers / name)
    for name in ("png.h", "pngconf.h"):
        shutil.copyfile(libpng / name, headers / name)
    shutil.copyfile(libpng / "scripts/pnglibconf.h.prebuilt", headers / "pnglibconf.h")
    # IJG's supplied ANSI C configuration matches the x86-64 musl target.
    shutil.copyfile(jpeg / "jconfig.txt", jpeg / "jconfig.h")
    shutil.copyfile(VENDOR / "testament.h", headers / "testament.h")

    builtin = subprocess.check_output([cc, "-print-file-name=include"], text=True).strip()
    flags = [cc, "-std=gnu11", "-Os", "-ffreestanding", "-fno-pie", "-fno-stack-protector",
             "-fno-asynchronous-unwind-tables", "-fno-unwind-tables", "-ffunction-sections", "-fdata-sections",
             "-mno-red-zone", "-nostdinc", "-isystem", builtin, "-isystem", sdk / "include", "-I", headers,
             "-U__linux__", "-U__linux", "-Ulinux", "-D__zenith__", "-D_GNU_SOURCE", "-DNDEBUG",
             "-D_ALIGNED=__attribute__((aligned))", "-DSTMTEXPR=1",
             "-ffile-prefix-map=" + str(out) + "=/netsurf"]
    units = []
    for name in LIBS:
        project = upstream / name
        sources = set((project / "src").rglob("*.c"))
        sources.discard(project / "src/parse/properties/css_property_parser_gen.c")
        sources.discard(project / "src/treebuilder/autogenerated-element-type.c")  # included by element-type.c
        if name == "libdom":
            sources.add(project / "bindings/hubbub/parser.c")
        for src in sorted(sources):
            units.append((src, ["-I", project, "-I", project / "src"]))
    for src in sorted(zlib.glob("*.c")):
        units.append((src, ["-DHAVE_UNISTD_H"]))
    for src in sorted(libpng.glob("png*.c")):
        units.append((src, ["-I", libpng]))
    for src in sorted(jpeg.glob("*.c")):  # decoder-only vendor subset
        units.append((src, []))
    listing = subprocess.check_output(["make", "-s", "-f", VENDOR / "core-sources.mk", "sources"], cwd=netsurf, text=True)
    core_flags = ["-I", netsurf, "-I", netsurf / "include", "-I", netsurf / "content/handlers",
                  "-I", netsurf / "generated-js", "-I", netsurf / "content/handlers/javascript/duktape",
                  "-I", jpeg, "-DWITH_BMP", "-DWITH_GIF", "-DWITH_PNG", "-DWITH_JPEG", "-DNETSURF_LOG_LEVEL=ERROR",
                  '-DNETSURF_HOMEPAGE="about:blank"', '-DNETSURF_BUILTIN_LOG_FILTER="level:ERROR"',
                  '-DNETSURF_BUILTIN_VERBOSE_FILTER="level:INFO"']
    units.extend((netsurf / name, core_flags) for name in sorted(set(listing.split())))

    def compile_unit(unit):
        src, options = unit
        dest = objects / ("__".join(src.relative_to(out).parts) + ".o")
        result = subprocess.run([*flags, *options, "-c", src, "-o", dest], stderr=subprocess.PIPE, text=True)
        if result.returncode:
            raise RuntimeError(f"Could not compile {src}:\n{result.stderr}")
        return dest

    with ThreadPoolExecutor(max_workers=jobs) as pool:
        futures = [pool.submit(compile_unit, unit) for unit in units]
        compiled, failures = [], []
        for future in futures:
            try:
                compiled.append(future.result())
            except RuntimeError as error:
                failures.append(str(error))
        if failures:
            raise SystemExit("\n".join(failures))
    temporary = out / "libnetsurf.new.a"
    temporary.unlink(missing_ok=True)
    run(["ar", "rcsD", temporary, *compiled])
    temporary.replace(out / "libnetsurf.a")
    stamp.write_text(key)
    print(f"Built {len(compiled)} target objects in {out / 'libnetsurf.a'}", flush=True)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output", type=Path, default=ROOT / "obj/netsurf-core")
    p.add_argument("--sdk", type=Path, default=ROOT / "obj/netsurf-sdk")
    p.add_argument("-j", type=int, default=min(8, os.cpu_count() or 1))
    args = p.parse_args()
    build(args.output.resolve(), args.sdk.resolve(), max(1, args.j))
